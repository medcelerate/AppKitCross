    static func characters(forKeyCode keyCode: UInt16, modifierFlags flags: NSEvent.ModifierFlags) -> String? {
        guard let row = us[keyCode] else { return nil }
        let shift = flags.contains(.shift), caps = flags.contains(.capsLock)
        let s: String
        if flags.contains(.control) { s = row[4] }
        else if flags.contains(.option) { s = shift ? row[3] : row[2] }
        else if caps { s = shift ? row[6] : row[5] }
        else { s = shift ? row[1] : row[0] }
        return s.isEmpty ? nil : s
    }
