#!/usr/bin/env python3
"""Embeds the Liquid Glass shader sources (ADR-0052 stage 2) into
Sources/AppKit/Platform/GlassShaders.swift.

  python3 tools/glass/embed-shaders.py [--spirv-dir DIR]

The Metal and HLSL programs are compiled at run time (Metal's newLibraryWithSource on the
macOS host, D3DCompile on Windows), so they are embedded as text. Vulkan wants SPIR-V, so
each GLSL compute shader (with glass_common.glsl) is compiled with glslangValidator (-V, Vulkan 1.3 target) and
embedded as 32-bit words, next to the FNV-1a hash of the GLSL it came from; a host test
recomputes the hashes, so a GLSL edit without a re-embed fails the suite. glslangValidator
runs from PATH, or from DIR when a previous run in the Linux container (tools/glass/
build-spirv.sh) left the .spv files there.
"""
import os, subprocess, sys, struct, tempfile, shutil

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SHADERS = os.path.join(ROOT, "Sources/AppKit/Platform/Shaders")
OUT = os.path.join(ROOT, "Sources/AppKit/Platform/GlassShaders.swift")
GLSL = ["glass_box", "glass_saturate", "glass_luminance", "glass_lens"]

def fnv1a(data: bytes) -> int:
    h = 0xcbf29ce484222325
    for b in data:
        h ^= b
        h = (h * 0x100000001b3) & 0xFFFFFFFFFFFFFFFF
    return h

def swift_string(text: str) -> str:
    # A raw multi-line string literal: no escapes are interpreted.
    assert '"""#' not in text
    return '#"""\n' + text.rstrip("\n") + '\n"""#'

def spirv_words(name, spirv_dir):
    src = os.path.join(SHADERS, name + ".comp")
    if spirv_dir:
        path = os.path.join(spirv_dir, name + ".spv")
    else:
        tool = shutil.which("glslangValidator")
        if not tool:
            sys.exit("glslangValidator not on PATH: run tools/glass/build-spirv.sh (Linux container) or pass --spirv-dir")
        path = os.path.join(tempfile.mkdtemp(), name + ".spv")
        subprocess.check_call([tool, "-V", "--target-env", "vulkan1.3", "-o", path, src])
    data = open(path, "rb").read()
    assert len(data) % 4 == 0 and struct.unpack_from("<I", data)[0] == 0x07230203, path
    return list(struct.unpack("<%dI" % (len(data) // 4), data))

def main():
    spirv_dir = None
    if "--spirv-dir" in sys.argv:
        spirv_dir = sys.argv[sys.argv.index("--spirv-dir") + 1]
    metal = open(os.path.join(SHADERS, "glass.metal"), encoding="utf-8").read()
    hlsl = open(os.path.join(SHADERS, "glass_lens.hlsl"), encoding="utf-8").read()
    backdrop = open(os.path.join(SHADERS, "glass_backdrop.hlsl"), encoding="utf-8").read()
    lines = [
        "// Generated by tools/glass/embed-shaders.py from Platform/Shaders: do not edit by hand.",
        "// The Liquid Glass programs (ADR-0052 stage 2): MSL and HLSL as text, the Vulkan",
        "// compute shaders as SPIR-V with the FNV-1a hash of their GLSL.",
        "",
        "enum _GlassShaders {",
        "    /// Platform/Shaders/glass.metal",
        "    static let metal = " + swift_string(metal).replace("\n", "\n    "),
        "    static let metalHash: UInt64 = 0x%016x" % fnv1a(metal.encode()),
        "    /// Platform/Shaders/glass_lens.hlsl",
        "    static let hlsl = " + swift_string(hlsl).replace("\n", "\n    "),
        "    static let hlslHash: UInt64 = 0x%016x" % fnv1a(hlsl.encode()),
        "    /// Platform/Shaders/glass_backdrop.hlsl",
        "    static let hlslBackdrop = " + swift_string(backdrop).replace("\n", "\n    "),
    ]
    for name in GLSL:
        # The hash covers the shared declarations too, which every shader includes.
        glsl = open(os.path.join(SHADERS, "glass_common.glsl"), "rb").read() + open(os.path.join(SHADERS, name + ".comp"), "rb").read()
        words = spirv_words(name, spirv_dir)
        ident = "".join(p.capitalize() if i else p for i, p in enumerate(name.split("_")))
        lines.append("    /// Platform/Shaders/%s.comp" % name)
        lines.append("    static let %sHash: UInt64 = 0x%016x" % (ident, fnv1a(glsl)))
        body = []
        for i in range(0, len(words), 8):
            body.append("        " + ", ".join("0x%08x" % w for w in words[i:i + 8]) + ",")
        lines.append("    static let %sSPIRV: [UInt32] = [" % ident)
        lines.extend(body)
        lines.append("    ]")
    lines.append("}")
    open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("wrote", os.path.relpath(OUT, ROOT))

main()
